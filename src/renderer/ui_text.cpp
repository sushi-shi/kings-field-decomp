#include <kf/renderer/ui_text.hpp>
#include <kf/renderer/renderer.hpp>
#include <kf/platform/host.hpp>

namespace kf {
void ui_text(const char *text, float x, float y, float scale, s32 depth) {
    // Five columns, seven rows, top pixel in bit zero.
    static constexpr u8 alphabet[26][5] = {
        {0x7e,0x09,0x09,0x09,0x7e}, {0x7f,0x49,0x49,0x49,0x36},
        {0x3e,0x41,0x41,0x41,0x22}, {0x7f,0x41,0x41,0x22,0x1c},
        {0x7f,0x49,0x49,0x49,0x41}, {0x7f,0x09,0x09,0x09,0x01},
        {0x3e,0x41,0x49,0x49,0x3a}, {0x7f,0x08,0x08,0x08,0x7f},
        {0x00,0x41,0x7f,0x41,0x00}, {0x20,0x40,0x41,0x3f,0x01},
        {0x7f,0x08,0x14,0x22,0x41}, {0x7f,0x40,0x40,0x40,0x40},
        {0x7f,0x02,0x0c,0x02,0x7f}, {0x7f,0x04,0x08,0x10,0x7f},
        {0x3e,0x41,0x41,0x41,0x3e}, {0x7f,0x09,0x09,0x09,0x06},
        {0x3e,0x41,0x51,0x21,0x5e}, {0x7f,0x09,0x19,0x29,0x46},
        {0x46,0x49,0x49,0x49,0x31}, {0x01,0x01,0x7f,0x01,0x01},
        {0x3f,0x40,0x40,0x40,0x3f}, {0x1f,0x20,0x40,0x20,0x1f},
        {0x3f,0x40,0x38,0x40,0x3f}, {0x63,0x14,0x08,0x14,0x63},
        {0x03,0x04,0x78,0x04,0x03}, {0x61,0x51,0x49,0x45,0x43}
    };
    for (; *text; ++text, x += 6 * scale) {
        if (*text < 'A' || *text > 'Z')
            continue;
        for (unsigned col = 0; col < 5; ++col)
            for (unsigned row = 0; row < 7; ++row) {
                if (!(alphabet[*text - 'A'][col] & (1u << row)))
                    continue;
                DrawFace face{};
                face.shape = FaceShape::Quad;
                face.depth = depth;
                const float left = x + col * scale, top = y + row * scale;
                face.vertices[0] = {left, top, 0, 0, 0.9f, 0.9f, 0.9f, 1};
                face.vertices[1] = {left + scale, top, 0, 0, 0.9f, 0.9f, 0.9f, 1};
                face.vertices[2] = {left, top + scale, 0, 0, 0.9f, 0.9f, 0.9f, 1};
                face.vertices[3] = {left + scale, top + scale, 0, 0, 0.9f, 0.9f, 0.9f, 1};
                host_enqueue_face(face);
            }
    }
}
}
